    private const val OP_HALT = 0xFF.toByte()
    private const val OP_MOV_IMM = 0x10.toByte()
    private const val OP_ADD_REG = 0x20.toByte()
    private const val OP_XOR_REG = 0x22.toByte()
    private const val OP_SBOX_SUB = 0x30.toByte()
    private const val OP_DECRYPT_BLOCK = 0x40.toByte()

    /**
     * Erzeugt Bytecode, der das Plaintext-Array zur Laufzeit entschlüsselt.
     */
    fun encrypt(plaintext: ByteArray): ByteArray {
        val bytecode = mutableListOf<Byte>()
        val registers = IntArray(4)
        val rand = Random()

        // 1. Register mit zufälligen Schlüsseln initialisieren
        for (i in 0 until 4) {
            registers[i] = rand.nextInt(256)
            bytecode.add(OP_MOV_IMM)
            bytecode.add(i.toByte())
            bytecode.add(registers[i].toByte())
        }

        // 2. Daten verarbeiten
        for (pByte in plaintext) {
            val p = pByte.toInt() and 0xFF

            // Junk-Code zur Obfuskation (ca. 20% Wahrscheinlichkeit)
            if (rand.nextInt(5) == 0) {
                val rx = rand.nextInt(4)
                val ry = rand.nextInt(4)
                when (rand.nextInt(3)) {
                    0 -> {
                        bytecode.add(OP_ADD_REG)
                        bytecode.add(rx.toByte())
                        bytecode.add(ry.toByte())
                        registers[rx] = (registers[rx] + registers[ry]) and 0xFF
                    }
                    1 -> {
                        bytecode.add(OP_XOR_REG)
                        bytecode.add(rx.toByte())
                        bytecode.add(ry.toByte())
                        registers[rx] = (registers[rx] xor registers[ry]) and 0xFF
                    }
                    2 -> {
                        bytecode.add(OP_SBOX_SUB)
                        bytecode.add(rx.toByte())
                        registers[rx] = SBOX[registers[rx]]
                    }
                }
            }

            // Maske berechnen
            val mask = registers[0] xor registers[1] xor registers[2] xor registers[3]
            val cipher = p xor mask

            // Entschlüsselungs-Opcode hinzufügen
            bytecode.add(OP_DECRYPT_BLOCK)
            bytecode.add(cipher.toByte())

            // Register-Zustand permutieren (Side Effects)
            registers[0] = (registers[0] + cipher) and 0xFF
            registers[1] = (registers[1] xor registers[0]) and 0xFF
            registers[2] = SBOX[registers[2]]
            registers[3] = SBOX[(registers[3] + 1) and 0xFF]
        }

        bytecode.add(OP_HALT)
        return bytecode.toByteArray()
    }
